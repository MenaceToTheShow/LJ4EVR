"""genfont.py - rasterise ASCII 32..126 into a 1-bit C header with a 13 px line height.

Spike-only font: Pillow's bundled open-licence TrueType face (Aileron) at 10 px,
which gives ascent 11 + descent 2 = 13 px, the MS Sans Serif 8 pt line height at
96 dpi (TextHeight = 13 in every DFM). Advance widths do NOT match MS Sans Serif;
the real project fits them to the DFM label corpus (see proposal, font section).

Usage: python -I genfont.py OUT.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

LINE_H = 13
font = ImageFont.load_default(size=10)
asc, desc = font.getmetrics()  # cell is 13 rows; descent rows beyond 13 are cropped

out = ["/* generated by tools/genfont.py - 1-bit glyphs, 13 px line height, ASCII 32..126 */",
       "#define FONT_LINE_H 13", "#define FONT_FIRST 32", "#define FONT_COUNT 95",
       "static const struct { unsigned char adv; unsigned short rows[13]; } FONT[95] = {"]
for code in range(32, 127):
    ch = chr(code)
    adv = max(1, round(font.getlength(ch)))
    img = Image.new("L", (16, LINE_H), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
    rows = []
    for y in range(LINE_H):
        bits = 0
        for x in range(16):
            if img.getpixel((x, y)) >= 128:
                bits |= 1 << x
        rows.append(bits)
    out.append("  {%d, {%s}}, /* %s */" % (adv, ",".join("0x%04x" % r for r in rows),
                                           ch if ch not in "*/\\" else "'" + ch + "'"))
out.append("};")
open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")
print("wrote", sys.argv[1])
