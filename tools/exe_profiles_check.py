#!/usr/bin/env python3
"""exe_profiles_check.py - the 201 exe profile rows (design 6.1 item 0, ME-8) and the
tier-1 hand-file coverage check (R19). Python 3 stdlib only.

    python -I tools/exe_profiles_check.py           # rewrite src/fixlib/lj_exe_profiles.c (needs reference/)
    python -I tools/exe_profiles_check.py --check   # CI: binding column vs hand/*.c + qxf_map.tsv,
                                                    # 201 rows ids 0-200, W1 tier-1 ids have a hand file;
                                                    # with reference/ present also diff against a regeneration

Inputs: reference/installer/exe_profile_table.txt (Martin data, gitignored; the table
is committed verbatim because the ids are LJ2's own Config.dat type codes),
src/fixlib/hand/*.c (a profile is `lj_profile <name> = { .id = N` or `= LJ_<MACRO>(N,`), tools/qxf_map.tsv.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "reference", "installer", "exe_profile_table.txt")
OUT = os.path.join(ROOT, "src", "fixlib", "lj_exe_profiles.c")
HAND = os.path.join(ROOT, "src", "fixlib", "hand")
MAP = os.path.join(ROOT, "tools", "qxf_map.tsv")
ROWS = 201
# Tier-1 ids a wave must cover by hand file (15-builtin-profiles-index.md, design 6.1 item 2).
W1_IDS = [12, 31, 24, 30,                                    # 15/01 MAC 500, MAC 500 SCRL, 918, 918 SCRL
          19, 70, 56, 71, 21, 72, 23, 20, 73, 22,            # 15/10 DMX Dimmer 1..32
          92, 93, 94, 95, 96, 97, 98, 99, 100, 101,          # DMX Switch Pack 1..32
          78, 135, 77, 76, 75,                               # RGB Pack x4 A/B, x6, x8, x10
          18, 45, 27, 90, 42, 43, 46]                        # Smoke, Hazer, SwitchBox 6, External, GCS 1, GSC 1, USER2
W2_IDS = [11, 67,                                            # 15/02 MAC 600, 600 NT
          28, 47, 39, 105, 112, 133, 48, 118,                # 15/03 MAC 250 family
          68, 84, 87, 88, 117, 161, 162, 188, 189, 190, 191, # 15/04 MAC 2000 family
          3, 58, 1, 52, 2, 57, 41, 36, 33]                   # 15/05 Roboscan 518 / 812 / 218 + the DMX-interface entries
WAVE_IDS = {1: W1_IDS, 2: W2_IDS}


def hand_ids():
    ids = set()
    for fn in sorted(os.listdir(HAND)):
        if fn.endswith(".c"):
            text = open(os.path.join(HAND, fn), encoding="latin-1").read()
            for m in re.finditer(r"lj_profile\s+\w+\s*=\s*(?:\{\s*\.id\s*=\s*(\d+)|LJ_\w+\(\s*(\d+))", text):
                ids.add(int(m.group(1) or m.group(2)))
    return ids


def map_ids():
    ids = set()
    if os.path.isfile(MAP):
        for line in open(MAP, encoding="ascii"):
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            ids.add(int(line.split("\t")[2]))
    return ids


def read_table():
    rows = []
    for line in open(TABLE, encoding="latin-1"):
        if not line.strip() or line.startswith("idx"):
            continue
        f = line.rstrip("\n").split(" | ")
        if len(f) != 6:
            f = line.rstrip("\n").split("|")      # the blank row 32 has no padding after the last bar
            f = [f[0]] + [x[1:] if x.startswith(" ") else x for x in f[1:]]
        idx = int(f[0])
        tag, man, name, mode, notes = (x.rstrip() for x in f[1:6])
        rows.append((idx, tag.strip(), man.strip(), name.strip(), mode, notes.strip()))   # mode keeps its leading space (15/10 s1)
    assert [r[0] for r in rows] == list(range(ROWS)), "exe table must hold ids 0..200"
    return rows


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(rows, hand, qmap):
    h = hashlib.sha256(open(TABLE, "rb").read()).hexdigest()[:16]
    out = ["/* lj_exe_profiles.c - generated by tools/exe_profiles_check.py; do not edit.",
           " * Input: reference/installer/exe_profile_table.txt (sha256 %s): the 201 built-in" % h,
           " * profile rows of LightJockey.exe 2.209 (ids 0-200 = LJ2's Config.dat type code), verbatim,",
           " * incl. the empty row 32 and the leading space of ' 1 Channel' [15/00 s1, 13 s2.7-2.8, D2].",
           " * binding = hand file (tier 1) / qxf_map.tsv (tier 2) / none (greyed), recomputed by the tool;",
           " * CI runs --check. */",
           '#include "fixlib/lj_exe_profiles.h"',
           "",
           "const lj_exe_row lj_exe_rows[LJ_EXE_ROWS] = {"]
    for idx, tag, man, name, mode, notes in rows:
        b = "LJ_BIND_HAND" if idx in hand else "LJ_BIND_QXF" if idx in qmap else "LJ_BIND_NONE"
        out.append("    { %3d, %s, %s, %s, %s, %s, %s }," % (idx, cstr(tag), cstr(man), cstr(name), cstr(mode), cstr(notes), b))
    out.append("};")
    return "\n".join(out) + "\n"


def committed_rows():
    """Parse the committed table back: (id, binding) pairs."""
    text = open(OUT, encoding="latin-1").read()
    return re.findall(r"^\s*\{\s*(\d+),.*?,\s*(LJ_BIND_\w+)\s*\},$", text, re.M)


def main():
    check = "--check" in sys.argv
    hand, qmap = hand_ids(), map_ids()
    bad = 0
    if check:
        rows = committed_rows()
        if [int(i) for i, _ in rows] != list(range(ROWS)):
            print("lj_exe_profiles.c: expected ids 0..200 in order, got %d rows" % len(rows)); bad += 1
        for i, b in rows:
            want = "LJ_BIND_HAND" if int(i) in hand else "LJ_BIND_QXF" if int(i) in qmap else "LJ_BIND_NONE"
            if b != want:
                print("id %s: binding %s, expected %s (regenerate: python -I tools/exe_profiles_check.py)" % (i, b, want)); bad += 1
        for wave, ids in WAVE_IDS.items():
            for i in ids:
                if i not in hand:
                    print("tier-1 id %d listed for W%d has no hand file under src/fixlib/hand/" % (i, wave)); bad += 1
        if os.path.isfile(TABLE):
            if render(read_table(), hand, qmap) != open(OUT, encoding="latin-1").read().replace("\r\n", "\n"):
                print("lj_exe_profiles.c differs from a regeneration"); bad += 1
        print("exe_profiles_check: %d rows, %d hand ids, %d map ids, %d finding(s)" % (len(rows), len(hand), len(qmap), bad))
        return 1 if bad else 0
    if not os.path.isfile(TABLE):
        print("no reference table at %s; nothing written" % TABLE)
        return 2
    text = render(read_table(), hand, qmap)
    with open(OUT, "w", encoding="latin-1", newline="\n") as f:
        f.write(text)
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
