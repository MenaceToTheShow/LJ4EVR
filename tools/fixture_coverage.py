#!/usr/bin/env python3
"""fixture_coverage.py - docs/fixtures/coverage.md: what the W7 fixture library ships per group (docs/fixtures.md).
Python 3 stdlib only.

    python -I tools/fixture_coverage.py           # write docs/fixtures/coverage.md
    python -I tools/fixture_coverage.py --check   # CI (once the catalogs are committed): exit 1 when the file is stale
    python -I tools/fixture_coverage.py --selftest

Inputs: docs/fixtures/catalog/<group>.tsv (columns model, category, status, modes_hint, manual_url,
source = qlc|ofl|authored|none, note; a missing catalog file is fine, the group then lists only what ships),
tools/qxf_map.tsv, the sources it names (tools/qxf2c.py), the hand rows of src/fixlib/lj_exe_profiles.c.
Per group: catalog models; shipped models and modes (hand rows + mapped modes); modes wider than 32 channels
(LJ_PROFILE_CH: never shipped) with their channel count; catalog models without a manual ("no manual").
A catalog model counts as shipped when its name matches a shipped model (qxf_map_sync.model_key) or its note
names a mapped source file (qlc:<file>.qxf, ofl:<file>.json, authored:<file>.qxf).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import qxf2c  # noqa: E402
import qxf_map_sync  # noqa: E402

CATALOG = os.path.join(qxf2c.ROOT, "docs", "fixtures", "catalog")
OUT = os.path.join(qxf2c.ROOT, "docs", "fixtures", "coverage.md")
COLS = ["model", "category", "status", "modes_hint", "manual_url", "source", "note"]


def read_catalogs():
    """-> {group: [row dict]}, [problem]."""
    out, problems = {}, []
    if not os.path.isdir(CATALOG):
        return out, problems
    for fn in sorted(os.listdir(CATALOG)):
        if not fn.endswith(".tsv"):
            continue
        g = qxf2c.group_of(fn[:-4])
        if g is None:
            problems.append("%s: not a W7 group" % fn)
            continue
        with open(os.path.join(CATALOG, fn), encoding="utf-8") as f:
            lines = f.read().splitlines()
        for ln, line in enumerate(lines[1:], 2):
            if not line.strip():
                continue
            v = line.split("\t")
            if len(v) < 6:
                problems.append("%s:%d: %d columns" % (fn, ln, len(v)))
                continue
            out.setdefault(g, []).append(dict(zip(COLS, v + [""] * (len(COLS) - len(v)))))
    return out, problems


def hand_rows():
    """Martin (and other group) exe rows bound to a hand file: (group, name, mode)."""
    text = open(qxf2c.EXE, encoding="latin-1").read()
    rows = []
    for m in re.finditer(r'^\s*\{\s*(\d+),\s*"[^"]*",\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*"[^"]*",\s*LJ_BIND_HAND', text, re.M):
        g = qxf2c.group_of(m.group(2))
        if g:
            rows.append((g, m.group(3), m.group(4)))
    return rows


def build(catalogs, scanned, rows, hand):
    """-> markdown text. scanned = qxf_map_sync.scan() list, rows = map lines, hand = hand_rows()."""
    info = {f: (g, mdl, dict(ms)) for f, g, mdl, ms in scanned}
    groups = [g for g, _, _ in qxf2c.GROUPS]
    shipped = {g: {} for g in groups}                     # group -> model key -> (display model, set of modes)
    files_mapped = set()
    for g, name, mode in hand:
        shipped[g].setdefault(qxf_map_sync.model_key(g, name), [name, set()])[1].add(("hand", mode))
    for f, m, pid in rows:
        if f not in info:
            continue
        g, mdl, _ = info[f]
        files_mapped.add(os.path.basename(f))
        shipped[g].setdefault(qxf_map_sync.model_key(g, mdl), [mdl, set()])[1].add((f, m))
    wide = {g: [] for g in groups}
    for f, (g, mdl, ms) in sorted(info.items()):
        for m, n in ms.items():
            if n > qxf2c.CH:
                wide[g].append((mdl, m, n, f))
    L = ["# Fixture coverage", "",
         "Generated by `tools/fixture_coverage.py` from `docs/fixtures/catalog/*.tsv`, `tools/qxf_map.tsv` and the sources it",
         "names; do not edit. A mode wider than 32 channels (`LJ_PROFILE_CH`, LightJockey 2's limit and the .GS2 format) is",
         "never shipped. \"no manual\": the catalog found no manufacturer manual, so nothing is authored from memory.", "",
         "| Group | Catalog models | Shipped models | Shipped modes | Catalog models shipped | Modes > 32 ch | No manual |",
         "|---|---:|---:|---:|---:|---:|---:|"]
    body = []
    for g in groups:
        cat = catalogs.get(g, [])
        ship = shipped[g]
        nmodes = sum(len(v[1]) for v in ship.values())
        hit, miss, noman = [], [], []
        for r in cat:
            refs = re.findall(r"\b(?:qlc|ofl|authored):([\w.+-]+\.(?:qxf|json))", r["note"])
            ok = qxf_map_sync.model_key(g, r["model"]) in ship or any(x in files_mapped for x in refs)
            (hit if ok else miss).append(r)
            if not r["manual_url"].strip() or r["manual_url"].strip().lower() == "none":
                noman.append(r)
        L.append("| %s | %d | %d | %d | %d | %d | %d |" % (g, len(cat), len(ship), nmodes, len(hit), len(wide[g]), len(noman)))
        body += ["", "## %s" % g, ""]
        if not cat:
            body.append("No catalog file yet: only what ships is listed.")
            body.append("")
        body.append("Shipped: %d models, %d modes (hand rows and mapped modes)." % (len(ship), nmodes))
        if miss:
            body += ["", "Catalog models not shipped (%d):" % len(miss), "", "| Model | Status | Source | Note |", "|---|---|---|---|"]
            body += ["| %s | %s | %s | %s |" % (esc(r["model"]), esc(r["status"]), esc(r["source"]), esc(r["note"])) for r in sorted(miss, key=lambda r: r["model"].lower())]
        if wide[g]:
            body += ["", "Modes wider than 32 channels, not shipped (%d):" % len(wide[g]), "", "| Model | Mode | Channels | Source |", "|---|---|---:|---|"]
            body += ["| %s | %s | %d | `%s` |" % (esc(mdl), esc(m), n, f) for mdl, m, n, f in sorted(wide[g], key=lambda w: (w[0].lower(), w[1].lower(), w[3]))]
        if noman:
            body += ["", "No manual (%d): %s." % (len(noman), ", ".join(esc(r["model"]) for r in sorted(noman, key=lambda r: r["model"].lower())))]
    return "\n".join(L + body) + "\n"


def esc(s):
    return s.replace("|", "\\|").strip()


def generate():
    catalogs, problems = read_catalogs()
    scanned, _ = qxf_map_sync.scan()
    return build(catalogs, scanned, qxf2c.read_map(), hand_rows()), problems


def selftest():
    scanned = [("A.qxf", "Martin", "MAC Foo", [("Basic", 12), ("Ext", 40)]), ("third_party/ofl-fixtures/glp/x.json", "GLP", "X4", [("M", 20)])]
    rows = [("A.qxf", "Basic", 1000)]
    cat = {"Martin": [dict(zip(COLS, ["MAC Foo", "spot", "current", "", "https://m/x.pdf", "qlc", ""])),
                      dict(zip(COLS, ["MAC Bar", "wash", "discontinued", "", "", "none", "no manual found"]))],
           "GLP": [dict(zip(COLS, ["impression X4", "wash", "current", "", "https://g/x.pdf", "ofl", "ofl:x.json"]))]}
    t = build(cat, scanned, rows, [("Martin", "MAC 500", "Mode 2/4")])
    assert "| Martin | 2 | 2 | 2 | 1 | 1 | 1 |" in t, t
    assert "| GLP | 1 | 0 | 0 | 0 | 0 | 0 |" in t and "| MAC Foo | Ext | 40 | `A.qxf` |" in t and "No manual (1): MAC Bar." in t, t
    assert build(cat, scanned, rows, []) == build(cat, scanned, rows, []), "not deterministic"
    print("fixture_coverage selftest: ok (catalog match by model and by note, > 32 ch listed, no manual)")
    return 0


def main():
    if "--selftest" in sys.argv:
        return selftest()
    text, problems = generate()
    for p in problems:
        print("note: %s" % p)
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read().replace("\r\n", "\n") if os.path.isfile(OUT) else None
        ok = old == text
        print("fixture_coverage --check: %s" % ("current" if ok else "docs/fixtures/coverage.md differs from a regeneration (run python -I tools/fixture_coverage.py)"))
        return 0 if ok else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s" % os.path.relpath(OUT, qxf2c.ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
